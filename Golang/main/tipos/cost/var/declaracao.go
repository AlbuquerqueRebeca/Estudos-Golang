package main

import "fmt"

func main() {

	nome := "Rebeca" //declarando uma variavel do tipo string
	fmt.Println(nome)

	numero := 20 //declarando uma variavel do tipo int
	fmt.Println(numero)

	var sobrenome string //declarando uma variavel do tipo string
	sobrenome = "guanaes"
	fmt.Println(sobrenome)

	sobrenome = "albuquerque" //acrescentando mais um valor a mesma variavel
	fmt.Println(sobrenome)

	altura := 1.65 //declarando uma variavel do tipo float
	fmt.Println(altura)
}
